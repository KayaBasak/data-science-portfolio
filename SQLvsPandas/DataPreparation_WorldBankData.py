import pandas as pd

# Load original World Bank data
df = pd.read_csv("world_bank_data.csv")

# Identify year columns
year_columns = [
    col for col in df.columns
    if "[YR" in col
]

# Convert wide format to long format
long_df = df.melt(
    id_vars=["Country Name", "Country Code",
             "Series Name", "Series Code"],
    value_vars=year_columns,
    var_name="Year",
    value_name="Value"
)

# Extract year
long_df["Year"] = (
    long_df["Year"].str.extract(r"(\d{4})").astype(int)
)

# Handle missing values
long_df["Value"] = (
    long_df["Value"].replace("..", pd.NA)
)

long_df["Value"] = pd.to_numeric(
    long_df["Value"], errors="coerce"
)

# Pivot indicators into separate columns
df_final = long_df.pivot(
    index=["Country Name", "Country Code", "Year"],
    columns="Series Code",
    values="Value"
).reset_index()

df_final.columns.name = None

# Rename columns
df_final = df_final.rename(columns={
    "Country Name": "country_name",
    "Country Code": "country_code",
    "Year": "year",
    "SP.POP.TOTL": "population",
    "NY.GDP.PCAP.PP.KD": "gdp_per_capita",
    "SP.DYN.LE00.IN": "life_expectancy",
    "SL.UEM.TOTL.NE.ZS": "unemployment_rate",
    "SP.URB.TOTL.IN.ZS": "urban_population_pct"
})

df_final.head()

import requests

# Retrieve country metadata from the World Bank API
url = "https://api.worldbank.org/v2/country"

response = requests.get(
    url,
    params={
        "format": "json",
        "per_page": 400
    }
)

data = response.json()

# Convert API response into a DataFrame
countries = pd.json_normalize(data[1])

# Keep country code, country name and region
regions = countries[
    ["id", "name", "region.value"]
].copy()

# Rename columns
regions = regions.rename(columns={
    "id": "country_code",
    "name": "country_name",
    "region.value": "region"
})

# Remove regional and income-group aggregates
regions = regions[
    regions["region"] != "Aggregates"
]

regions.head()

df_final = df_final.merge(
    regions[["country_code", "region"]],
    on="country_code",
    how="left",
    validate="many_to_one"
)

df_final.head()

# Check missing regions
