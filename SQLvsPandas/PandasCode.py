import pandas as pd

# Reading the csv file
df = pd.read_csv('world_bank_prepared.csv')

# First 5 rows
df.head()

"""# Part 1. Basic Operations

## 1. Selecting Columns

**Question:** What are the country names, regions, and population figures in our dataset?
"""

df[['country_name', 'region', 'population']]

"""##2. Selecting Unique Values

**Question:** Which unique regions are represented in our dataset?
"""

df['region'].unique()

df['region'].drop_duplicates()

"""## 3. Filtering Rows

**Question:** Which countries had a population greater than 50 million in 2024?
"""

filtered_df = df[
    (df['year'] == 2024) &
     (df['population'] > 50000000)
]

filtered_df[['country_name', 'population']]

"""## 4.  Filtering with Multiple Conditions

**Question:** Which countries had GDP per capita above 30,000 international dollars AND life expectancy above 80 years in 2024?
"""

filtered_df = df[
    (df['year'] == 2024) &
    (df['gdp_per_capita'] > 30000) &
    (df['life_expectancy'] > 80)
]

filtered_df[['country_name', 'gdp_per_capita', 'life_expectancy']]

"""## 5. Filtering Multiple Values

**Question:** What are the population figures for Canada, Germany, Japan, and Australia in 2024?
"""

filtered_df = df[
    (df['year'] == 2024) &
    df['country_name'].isin(['Canada', 'Germany', 'Japan', 'Australia'])
]

filtered_df[['country_name', 'population']]

"""## 6. Filtering a Range of Values

**Question:** Which countries had GDP per capita between 20,000 and 40,000 international dollars in 2024?
"""

filtered_df = df[
    (df['year'] == 2024) &
    (df['gdp_per_capita'].between(20000, 40000))
]

filtered_df[['country_name', 'gdp_per_capita']]

filtered_df = df[
    (df['year'] == 2024) &
    (df['gdp_per_capita'] > 20000) &
    (df['gdp_per_capita'] < 40000)
]

filtered_df[['country_name', 'gdp_per_capita']]

"""## 7. Sorting Data

**Question:** Which countries had the highest GDP per capita in 2024?
"""

filtered_df = df[df['year'] == 2024]

filtered_df[['country_name', 'gdp_per_capita']].sort_values(
    by='gdp_per_capita', ascending=False)

"""Sorting by multiple columns"""

filtered_df = df[df['year'] == 2024]

filtered_df[['country_name', 'gdp_per_capita', 'region']].sort_values(
    by=['region', 'gdp_per_capita'], ascending = [True, False])

"""## 8. Limiting Results

**Question:** What are the five most populous countries in 2024?
"""

filtered_df = df[df['year'] == 2024]

filtered_df.sort_values(by='population', ascending=False).head(5)

"""# Part 2: Data Cleaning

## 1. Identifying Missing Values

**Question:** Which countries have missing unemployment data in 2024?
"""

df_2024 = df[df['year'] == 2024]

df_2024[
    df_2024['unemployment_rate'].isna()
][['country_name', 'unemployment_rate']]

"""## 2. Handling Missing Values

**Question:** How can we replace missing unemployment values with a default value?
"""

df_2024 = df[df['year'] == 2024]

df_2024['unemployment_filled'] = df_2024['unemployment_rate'].fillna(-1)

df_2024[['country_name', 'unemployment_rate', 'unemployment_filled']]

"""## 3. Removing Duplicates

**Question:** Are there duplicate country-year records in our dataset?
"""

df.duplicated(
    subset=['country_code', 'year']
).sum()

"""Removing duplicate country-year records"""

df_cleaned = df.drop_duplicates(
    subset=['country_code', 'year']
)

"""## 4. Renaming Columns

**Question:** How can we rename columns to make our dataset easier to understand?
"""

df_renamed = df.rename(columns={
    'country_name':'country',
    'country_code':'iso_code',
    'population':'total_population'
})

df_renamed.head(10)

"""## 5. Creating Conditional Columns

**Question:** How can we categorize countries according to their GDP per capita in 2024?
"""

import numpy as np

df_2024 = df[df['year'] == 2024]

df_2024['gdp_category'] = np.select(
    [
        df_2024['gdp_per_capita'].isna(),
        df_2024['gdp_per_capita'] < 15000,
        df_2024['gdp_per_capita'] <= 40000
    ],
    [
        'Unknown',
        'Low',
        'Medium'
    ],
    default='High'
)

df_2024[['country_name', 'gdp_per_capita', 'gdp_category']]

"""# Part 3. Data Aggregation

## 1. Grouping Data

**Question:** What is the average life expectancy in each region in 2024?
"""

df_2024 = df[df['year'] == 2024]

df_2024.groupby('region')['life_expectancy'].mean().sort_values(ascending=False)

"""## 2. Aggregate Functions

**Question:** What are the total population, average GDP per capita, and maximum life expectancy in each region in 2024?
"""

df_2024 = df[df['year'] == 2024]

df_2024.groupby('region').agg(
    total_population = ('population', 'sum'),
    avg_gdp_per_capita = ('gdp_per_capita', 'mean'),
    max_life_expectancy = ('life_expectancy', 'max')
)

"""## 3. Multiple Aggregations

**Question:** What are the average, minimum, and maximum GDP per capita values in each region in 2024?
"""

df_2024 = df[df['year'] == 2024]

df_2024.groupby('region')['gdp_per_capita'].agg(
    ['mean', 'min', 'max']
)

"""## 4. Filtering Aggregated Results

**Question:** Which regions had an average life expectancy above 80 years in 2024?
"""

df_2024 = df[df['year'] == 2024]

avg_life = df_2024.groupby('region')['life_expectancy'].mean()

avg_life[avg_life > 80]

"""## 5. Conditional Aggregation

**Question:** How many countries in each region had an unemployment rate above 10% in 2024?
"""

df_2024 = df[df['year'] == 2024]

df_2024.groupby('region').agg(
    high_unemployment = (
        'unemployment_rate',
        lambda x: (x > 10).sum()
    )
)

"""# Putting It All Together

## Practical Example

**Question:** Which countries in each region had a population above 50 million and GDP per capita above 20,000 international dollars in 2024? Show their population, GDP per capita, and life expectancy, and sort the results by region and GDP per capita.
"""

filtered_df = df[
    (df['year'] == 2024) &
    (df['population'] > 50000000) &
    (df['gdp_per_capita'] > 20000)
]

result = filtered_df[
    [
      'country_name',
      'region',
      'population',
      'gdp_per_capita',
      'life_expectancy'
    ]
].sort_values(
    by=['region', 'gdp_per_capita'],
    ascending=[True, False]
)

result
